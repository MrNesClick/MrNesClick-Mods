#!/usr/bin/env python3
"""Turns a NeoForge/Forge config file (TOML with its generated comments) into a Markdown reference.

  python3 tools/config_reference.py <config.toml> <title> > docs/<mod>/config-tables.md

Use a freshly generated file, so that every value is the default. Each [section] becomes a heading with one table:
option, default, allowed range or values, description. Section comments (the lines just before the header) become
the section text.
"""
import re
import sys

META = re.compile(r"^(Default|Range|Allowed Values):\s*(.*)$")


def cell(text):
    return text.replace("|", "\\|").strip()


def parse(path):
    sections = []  # (name, description lines, options)
    current = ("", [], [])
    pending = []
    for raw in open(path, encoding="utf-8"):
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            pending.append(line[1:].strip())
            continue
        header = re.fullmatch(r"\[([^\]]+)\]", line)
        if header:
            if current[0] or current[2]:
                sections.append(current)
            current = (header.group(1), [p for p in pending if not META.match(p)], [])
            pending = []
            continue
        key, value = (part.strip() for part in line.split("=", 1))
        description = [p for p in pending if not META.match(p)]
        limits = [m.group(2) for p in pending if (m := META.match(p)) and m.group(1) != "Default"]
        current[2].append((key, value, ", ".join(limits), " ".join(description)))
        pending = []
    sections.append(current)
    return sections


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    path, title = sys.argv[1], sys.argv[2]
    out = [f"<!-- Generated by tools/config_reference.py from the default {title} config: do not edit by hand. -->", ""]
    for name, description, options in parse(path):
        if not options:
            # A parent section with only subsections: its text goes before them.
            if description:
                out += [f"## `[{name}]`", "", " ".join(description), ""]
            continue
        level = "##" if "." not in name else "###"
        out += [f"{level} `[{name}]`", ""]
        if description:
            out += [" ".join(description), ""]
        out += ["| Option | Default | Range or values | Description |", "|---|---|---|---|"]
        for key, value, limits, text in options:
            out.append(f"| `{cell(key)}` | `{cell(value)}` | {cell(limits)} | {cell(text)} |")
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
