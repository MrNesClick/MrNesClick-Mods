#!/usr/bin/env python3
"""Refreshes the configuration reference of a mod from its source repository, at each release of that mod.

  python3 tools/sync_config.py <mod> [--source DIR] [--skip-build]
  python3 tools/sync_config.py all

Run it when a mod is released, with the mod repository at the release commit: the docs describe the released
version, not work in progress.

<mod> is a docs folder: mekanistic-geothermal, flux-networks-extended or mcnesclick. The mod repositories are
private and sit next to this one (../MCMekanisticGeothermal...), or wherever --source points.

For each config file of the mod:
1. a fresh default file is generated from the mod itself (GameTest server, or the config class for MCNesclick).
   The config file already in the mod's dev run is moved aside first and put back afterwards, even on failure,
   so that dev settings are never lost;
2. it is copied to tools/defaults/<mod>/ and turned into tables in tools/generated/<mod>/ (tools/config_reference.py);
3. the site is built with `mkdocs build --strict` (mkdocs from PATH or .venv/), which checks links and anchors.

Then review `git diff`, update the pages (English and French) if options were added or removed, and commit.
"""
import argparse
import pathlib
import shutil
import subprocess
import sys
import tempfile

DOCS = pathlib.Path(__file__).resolve().parent.parent

# Each file: path in the mod repository, generated page name, title of the tables, and whether a fresh default can be
# generated. A client config file cannot come from a headless run: it is taken from the bot client's run (the headless client of
# MCDevKit, never edited by hand) and its diff must be read before committing.
MODS = {
    "mekanistic-geothermal": dict(
        repo="MCMekanisticGeothermal",
        gradle=["./gradlew", "runGameTestServer"],
        files=[
            ("run/gametest/config/mekanismgeothermal-server.toml", "server", "server", True),
            ("run/client-bot/config/mekanismgeothermal-client.toml", "client", "client", False),
        ],
    ),
    "flux-networks-extended": dict(
        repo="MCFluxNetworksExtended",
        gradle=["./gradlew", ":1.21.1-neoforge:runGameTestServer"],
        files=[("versions/1.21.1-neoforge/run/config/fluxnetworksextended-server.toml", "server", "server", True)],
    ),
    "mcnesclick": dict(
        repo="MCNesClick",
        config_class="common/java/com/mrnesclick/mcnesclick/config/MCNesclickConfig.java",
        files=[("mcnesclick.toml", "config", "MCNesclick", True)],
    ),
}

# Calls the config class's init(dir), which writes every option with its default value.
INIT_MAIN = """public class InitConfig {
    public static void main(String[] args) {
        com.mrnesclick.mcnesclick.config.MCNesclickConfig.init(java.nio.file.Path.of(args[0]));
    }
}
"""


def run(command, cwd):
    print("$", " ".join(command), flush=True)
    subprocess.run(command, cwd=cwd, check=True)


def gradle_defaults(source, mod, scratch):
    """Runs the GameTest server with the generated files moved aside; returns {relative path: fresh file}."""
    generated = [path for path, _, _, fresh in mod["files"] if fresh]
    saved = {}
    try:
        for path in generated:
            current = source / path
            if current.exists():
                saved[path] = scratch / ("saved-" + current.name)
                shutil.move(current, saved[path])
        run(mod["gradle"], source)
        result = {}
        for path in generated:
            if not (source / path).exists():
                sys.exit(f"{path} was not generated by {' '.join(mod['gradle'])}")
            result[path] = scratch / pathlib.PurePath(path).name
            shutil.copy(source / path, result[path])
        return result
    finally:
        for path, backup in saved.items():
            shutil.move(backup, source / path)


def class_defaults(source, mod, scratch):
    """Compiles the config class alone (plain Java) and lets it write its default file."""
    classes, config = scratch / "classes", scratch / "config"
    config.mkdir()
    (scratch / "InitConfig.java").write_text(INIT_MAIN)
    run(["javac", "-d", str(classes), str(source / mod["config_class"]), str(scratch / "InitConfig.java")], scratch)
    run(["java", "-cp", str(classes), "InitConfig", str(config)], scratch)
    return {path: config / path for path, _, _, _ in mod["files"]}


def mkdocs():
    found = shutil.which("mkdocs")
    local = DOCS / ".venv" / "bin" / "mkdocs"
    return found or (str(local) if local.exists() else None)


def sync(name, source):
    mod = MODS[name]
    source = (source or DOCS.parent / mod["repo"]).resolve()
    if not source.is_dir():
        sys.exit(f"{source} not found: give the mod repository with --source")
    print(f"== {name} from {source}")
    defaults, generated = DOCS / "tools" / "defaults" / name, DOCS / "tools" / "generated" / name
    defaults.mkdir(parents=True, exist_ok=True)
    generated.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        scratch = pathlib.Path(tmp)
        fresh = class_defaults(source, mod, scratch) if "config_class" in mod else gradle_defaults(source, mod, scratch)
        for path, page, title, is_fresh in mod["files"]:
            origin = fresh[path] if is_fresh else source / path
            if not origin.exists():
                sys.exit(f"{origin} not found")
            if not is_fresh:
                print(f"! {path} comes from a dev run: check in git diff that it holds default values only")
            target = defaults / pathlib.PurePath(path).name
            shutil.copy(origin, target)
            table = generated / (page + ".md")
            with open(table, "w", encoding="utf-8") as out:
                subprocess.run([sys.executable, str(DOCS / "tools" / "config_reference.py"), str(target), title],
                               stdout=out, check=True)
            print(f"  {target.relative_to(DOCS)} -> {table.relative_to(DOCS)}")


def build():
    command = mkdocs()
    if command is None:
        print("! mkdocs not found: python3 -m venv .venv && .venv/bin/pip install -r requirements.txt, then run again")
        return
    with tempfile.TemporaryDirectory() as site:
        run([command, "build", "--strict", "--quiet", "-d", site], DOCS)
    print("site built: links and anchors are fine")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("mod", choices=[*MODS, "all"])
    parser.add_argument("--source", type=pathlib.Path, help="the mod repository (default: next to this one)")
    parser.add_argument("--skip-build", action="store_true", help="do not build the site afterwards")
    args = parser.parse_args()
    if args.mod == "all" and args.source:
        sys.exit("--source needs a single mod")
    for name in MODS if args.mod == "all" else [args.mod]:
        sync(name, args.source)
    if not args.skip_build:
        build()
    subprocess.run(["git", "status", "--short", "tools"], cwd=DOCS)


if __name__ == "__main__":
    main()
